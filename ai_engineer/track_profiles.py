_calibration_cache: dict[str, Any] | None = None


def load_calibration(path: Path | None = None, *, reload: bool = False) -> dict[str, Any]:
    """Measured real-race values from the calibration file ({} when it does not exist)."""
    global _calibration_cache
    if path is not None:
        try:
            return json.loads(Path(path).read_text(encoding='utf-8'))
        except (OSError, ValueError):
            return {}
    if _calibration_cache is None or reload:
        try:
            _calibration_cache = json.loads(CALIBRATION_PATH.read_text(encoding='utf-8'))
        except (OSError, ValueError):
            _calibration_cache = {}
    return _calibration_cache


def get_profile(track_id: int, calibration: dict[str, Any] | None = None) -> dict[str, Any] | None:
    """Baseline profile for a circuit with any measured real-race values layered on top.

    The result carries ``source`` ('pirelli_baseline' or 'fastf1') and, when calibrated,
    ``measured`` with the raw numbers and the races they came from.
    """
    base = BASELINE_PROFILES.get(track_id)
    if base is None:
        return None
    profile = dict(base)
    profile['source'] = 'pirelli_baseline'
    measured = (calibration if calibration is not None else load_calibration()).get('tracks', {}).get(str(track_id))
    if measured:
        profile['measured'] = measured
        profile['source'] = 'fastf1'
        for key in ('pit_loss_s', 'sc_probability', 'rain_probability', 'race_laps'):
            if measured.get(key) is not None:
                profile[key] = measured[key]
    return profile
