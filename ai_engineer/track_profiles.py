"""
Real-race circuit profiles
==========================
What each circuit actually does to a car and its tyres, as measured in real Grands Prix.
The track analysis model (track_analysis.py) turns these into per-track tyre degradation,
stint lengths, pit strategy and wet/dry setups, and DeepSeek reasons over them.

Two layers:

* ``BASELINE_PROFILES`` (below) - hand-entered from Pirelli's published circuit severity
  ratings (1-5 scales) and real 2018-2023 race history: race laps, pit-lane time loss,
  how often a Safety Car came out, how often it rained, typical track temperature.

* ``data/real_race_calibration.json`` - optional, generated by
  ``tools/build_real_race_calibration.py`` from real race timing data loaded through FastF1
  (the same data source IAmTomShaw/f1-race-replay replays). Measured values in that file
  override the baseline for that circuit, e.g. the fuel-corrected degradation rate of each
  compound, the median number of stops and the measured pit loss.

Keys are TRACK_DATABASE ids (game track ids; short layouts resolve to their parent).
"""

